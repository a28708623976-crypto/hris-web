import assert from "node:assert/strict";
import { createInitialState, useStore } from "../src/store";
import { calibratePerformance, syncPerformancePayroll } from "../src/store/performance";
import { payrollSummary } from "../src/utils/payroll";
useStore.setState(createInitialState());
const initial = payrollSummary(useStore.getState().employees).totalGross;
assert.equal(calibratePerformance("EMP005", "B+ (4.2)", "跨团队协作达标"), true);
assert.equal(useStore.getState().perfRecords.find(r => r.id === "EMP005")?.status, "已校准");
assert.equal(useStore.getState().employees.find(e => e.id === "EMP005")?.payrollPerformance, undefined);
assert.equal(syncPerformancePayroll(), true);
const employee = payrollSummary(useStore.getState().employees).activeList.find(e => e.id === "EMP005")!;
assert.deepEqual(employee.payrollPerformance, { grade: "B+ (4.2)", managerComment: "跨团队协作达标", okrProgress: 95 });
assert.equal(payrollSummary(useStore.getState().employees).totalGross, initial);
assert.equal(useStore.getState().employees.find(e => e.id === "EMP009")?.payrollPerformance, undefined);
assert.equal(calibratePerformance("missing", "S (4.9)", ""), false);
assert.equal(calibratePerformance("EMP005", "invalid", ""), false);
useStore.setState({ role: "普通员工" });
const before = useStore.getState();
assert.equal(calibratePerformance("EMP005", "S (4.9)", ""), false);
assert.equal(syncPerformancePayroll(), false);
assert.equal(useStore.getState(), before);
useStore.setState({ role: "部门负责人" });
assert.equal(calibratePerformance("EMP005", "A (4.6)", "负责人校准"), true);
useStore.setState(createInitialState());
console.log("PASS 13 performance state checks: calibration, genuine payroll inputs, unchanged salary basis, roles.");
